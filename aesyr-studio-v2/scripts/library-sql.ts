// Generates the SQL that upserts the built-in library entries (shared/narratives.ts and
// shared/scene-presets.ts) into public.library_entries.
//   npx tsx scripts/library-sql.ts > supabase/migrations/<timestamp>_library_builtins.sql
// tests/db checks the newest *_library_builtins.sql migration still matches this output, so a
// change to a built-in fails CI until a new seed migration is generated.
import { NARRATIVES } from "../shared/narratives";
import { SCENE_PRESETS } from "../shared/scene-presets";

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function librarySeedSql(): string {
  const rows = [
    ...NARRATIVES.map((n) => ({ kind: "narrative", slug: n.id, name: n.name, version: n.version, data: n })),
    ...SCENE_PRESETS.map((p) => ({ kind: "scene_preset", slug: p.id, name: p.name, version: p.version, data: p })),
  ];
  const values = rows
    .map((r) => `  (${lit(r.kind)}, 'builtin', ${lit(r.slug)}, ${lit(r.name)}, ${r.version}, ${lit(JSON.stringify(r.data))}::jsonb)`)
    .join(",\n");
  return `-- Built-in library entries (generated by scripts/library-sql.ts; do not edit by hand).
insert into public.library_entries (kind, scope, slug, name, version, data)
values
${values}
on conflict (kind, slug) where scope = 'builtin'
do update set name = excluded.name, version = excluded.version, data = excluded.data, updated_at = now();
`;
}

if (process.argv[1]?.replace(/\\/g, "/").endsWith("scripts/library-sql.ts")) process.stdout.write(librarySeedSql());
